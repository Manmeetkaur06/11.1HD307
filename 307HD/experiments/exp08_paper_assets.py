def build(r, M):
    rep, allm = r["rep"], r["all"]
    names = {"roc_auc": "AUC"}
    # --- Table: published vs reproduced (seed 42, Protocol A)
    lines = []
    for model in ALL_MODELS:
        pub = PUBLISHED[model]
        ours = [r["repro"].loc[model, m] for m in METRICS]
        cells = []
        for p, o in zip(pub, ours):
            cells += [f3(p), f3(o), sgn(o - p)]
        label = "Stack" if model == "Stacking" else model
        if model == "Stacking":
            lines.append("\\midrule")
        lines.append(f"{label} & " + " & ".join(cells) + "\\\\")
    write_tab("repro", lines)
    rp = r["repro"]
    M("ReproStackAcc", f"{rp.loc['Stacking','accuracy']:.4f}")
    M("ReproStackAccPct", f"{100*rp.loc['Stacking','accuracy']:.2f}")
    M("ReproStackRec", f3(rp.loc["Stacking", "recall"]))
    for m in ("DT", "RF", "XGB"):
        M(f"ReproGain{m}", f"{100*(rp.loc[m,'accuracy']-PUBLISHED[m][0]):.1f}")
    losses = [100 * (PUBLISHED[m][0] - rp.loc[m, "accuracy"]) for m in ("LR", "NB", "KNN")]
    M("ReproLossMin", f"{min(losses):.1f}"); M("ReproLossMax", f"{max(losses):.1f}")
    a42 = anchor(allm, "A", "Stacking")
    for k in ("tn", "fp", "fn", "tp"):
        M(f"AnchorA{k.upper()}", int(a42[k]))
    M("AnchorANeg", int(a42.tn + a42.fp)); M("AnchorAPos", int(a42.fn + a42.tp))
    mu, sd = stat(rep, "A", "Stacking", "accuracy")
    M("AStackAccPct", f"{100*mu:.2f}"); M("AStackAccSDPct", f"{100*sd:.2f}")
    M("AStackAUC", f3(stat(rep, "A", "Stacking", "roc_auc")[0]))

    # --- Table: stacking discrepancy (Table 12 vs Fig 5 vs ours)
    ours = {}
    for arm in ("A", "C"):
        s = anchor(allm, arm, "Stacking")
        cm = counts_metrics(s.tn, s.fp, s.fn, s.tp)
        cm["roc_auc"] = s.roc_auc
        ours[arm] = cm
    fig5 = counts_metrics(**FIG5)
    lines = []
    for key, label in [("sensitivity", "Sensitivity"), ("specificity", "Specificity"), ("precision", "Precision"),
                       ("accuracy", "Accuracy"), ("f1", "F1"), ("roc_auc", "AUC"), ("mcc", "MCC")]:
        f5 = "---" if key == "roc_auc" else f"{fig5[key]:.4f}"
        lines.append(f"{label} & {TABLE12[key]:.4f} & {f5} & {ours['A'][key]:.4f} & {ours['C'][key]:.4f}\\\\")
    write_tab("discrep", lines)

    # --- Table: A vs C means
    best = {m: max(ALL_MODELS, key=lambda mod: stat(rep, "C", mod, m)[0]) for m in METRICS}
    lines = []
    for model in ALL_MODELS:
        cells = [pm(*stat(rep, "A", model, m)) for m in METRICS]
        for m in METRICS:
            c = pm(*stat(rep, "C", model, m))
            cells.append(f"\\textbf{{{c}}}" if best[m] == model else c)
        label = "Stack" if model == "Stacking" else model
        if model == "Stacking":
            lines.append("\\midrule")
        lines.append(f"{label} & " + " & ".join(cells) + "\\\\")
    write_tab("avc", lines)
    c_lr, c_st = stat(rep, "C", "LR", "accuracy")[0], stat(rep, "C", "Stacking", "accuracy")[0]
    M("CLRAcc", f3(c_lr)); M("CLRAUC", f3(stat(rep, "C", "LR", "roc_auc")[0]))
    M("CDTAcc", f3(stat(rep, "C", "DT", "accuracy")[0]))
    M("CStackAcc", f3(c_st)); M("CStackBelowLR", f"{100*(c_lr-c_st):.2f}")
    x = con(r, "C stack-C NB")
    M("CStackNBWins", int(x.wins)); M("CStackNBTies", words(int(x.ties))); M("CStackNBLosses", words(int(x.losses)))
    x = con(r, "C stack-C LR")
    M("CStackLRWins", int(x.wins)); M("CStackLRTies", words(int(x.ties))); M("CStackLRLosses", int(x.losses))
    drops = [100 * (stat(rep, "A", m, "accuracy")[0] - stat(rep, "C", m, "accuracy")[0]) for m in ALL_MODELS]
    M("DropMin", f"{min(drops):.0f}"); M("DropMax", f"{max(drops):.0f}")
    M("AdvantageOverLR", f"{100*(stat(rep,'A','Stacking','accuracy')[0]-stat(rep,'A','LR','accuracy')[0]):.0f}")

    # --- Table: C-B paired + E3
    lines = []
    labels = {"accuracy": "Accuracy", "precision": "Precision", "recall": "Recall", "f1": "F1", "roc_auc": "AUC"}
    for m in METRICS:
        x = con(r, "C-B stack", m)
        lines.append(f"{labels[m]} & {sgn(x.mean_pp,2)}\\,$\\pm$\\,{x.sd_pp:.2f} & {x.wins} & {x.ties} & {x.losses}\\\\")
        tag = {"accuracy": "Acc", "precision": "Prec", "recall": "Rec", "f1": "Fone", "roc_auc": "AUC"}[m]
        M(f"CB{tag}Diff", sgn(x.mean_pp, 2)); M(f"CB{tag}Wins", int(x.wins))
    x = con(r, "C-B stack")
    M("CBTies", words(int(x.ties))); M("CBLosses", words(int(x.losses)))
    M("CBPcorr", f3(x.p_corr)); M("CBTcorr", f"{x.t_corr:.2f}"); M("CBWilcoxon", f3(x.wilcoxon_p))
    M("BStackAcc", f3(stat(rep, "B", "Stacking", "accuracy")[0]))
    M("BStackAccPct", pct(stat(rep, "B", "Stacking", "accuracy")[0]))
    M("CStackAccPct", pct(c_st))
    lines += ["\\midrule", "\\multicolumn{5}{@{}l}{\\textit{Inner-fold count (E3), accuracy}}\\\\"]
    from src.evaluation import corrected_t, win_tie_loss
    e3 = r["e3"]
    for k, word in ((3, "Three"), (5, "Five"), (10, "Ten")):
        b = e3[(e3.k == k) & (e3.arm == "B")].set_index("seed").accuracy.loc[SEEDS]
        c = e3[(e3.k == k) & (e3.arm == "C")].set_index("seed").accuracy.loc[SEEDS]
        d = (c - b).to_numpy() * 100
        w, _, _ = win_tie_loss(d)
        _, p = corrected_t(d, 61 / 241)
        lines.append(f"$k={k}$ & {sgn(d.mean(),2)}\\,$\\pm$\\,{d.std(ddof=1):.2f} & {w} & "
                     f"\\multicolumn{{2}}{{c}}{{($p_\\text{{corr}}={p:.3f}$)}}\\\\")
        M(f"EthreeDiff{word}", sgn(d.mean(), 2)); M(f"EthreeWins{word}", w)
    write_tab("cb", lines)

    # --- mechanism macros (OOF accuracy and coefficients)
    meta = r["meta"][r["meta"].seed.isin(SEEDS)]
    for arm in ("B", "C"):
        sub = meta[meta.arm == arm]
        for n in MODEL_ORDER:
            M(f"Coef{arm}{n}", f"{sub['coef_'+n].mean():.2f}".replace("-", "$-$"))
            M(f"Oof{arm}{n}", f3(sub["oof_acc_" + n].mean()))

    # --- Table: combiner control (E2)
    e2 = r["e2"]

    def comb(cb, arm, m):
        s = e2[(e2.combiner == cb) & (e2.arm == arm)].set_index("seed")[m].loc[SEEDS]
        return s.mean(), s.std(ddof=1)
    lines = [f"Soft vote (no OOF) & B$\\,=\\,$C & " + " & ".join(pm(*comb("soft_vote", "B", m))
                                                            for m in METRICS) + "\\\\",
             "\\addlinespace"]
    for cb, label in (("oof_best_single", "OOF-selected learner"), ("lr_meta", "LR meta-learner (stack)")):
        for i, arm in enumerate(("B", "C")):
            cells = [pm(*comb(cb, arm, m)) for m in METRICS]
            if cb == "lr_meta" and arm == "C":
                cells = [f"\\textbf{{{c}}}" for c in cells]
            lines.append(f"{label if i == 0 else ''} & {arm} & " + " & ".join(cells) + "\\\\")
        if cb == "oof_best_single":
            lines.append("\\addlinespace")
    write_tab("combiner", lines)
    soft = comb("soft_vote", "B", "accuracy")[0]
    M("SoftAcc", f3(soft)); M("SoftAccPct", pct(soft))
    for cb, tag in (("oof_best_single", "Best"), ("lr_meta", "LR")):
        for m, mt in (("accuracy", "Acc"), ("roc_auc", "AUC")):
            b = e2[(e2.combiner == cb) & (e2.arm == "B")].set_index("seed")[m].loc[SEEDS]
            c = e2[(e2.combiner == cb) & (e2.arm == "C")].set_index("seed")[m].loc[SEEDS]
            M(f"Etwo{tag}Diff{mt}", sgn(100 * (c - b).mean(), 2))
    softs = e2[(e2.combiner == "soft_vote") & (e2.arm == "B")].set_index("seed").accuracy.loc[SEEDS]
    for arm in ("B", "C"):
        lr = e2[(e2.combiner == "lr_meta") & (e2.arm == arm)].set_index("seed").accuracy.loc[SEEDS]
        d = (lr - softs).to_numpy() * 100
        w, _, lo = win_tie_loss(d)
        M(f"MinusSoft{arm}", sgn(d.mean(), 2)); M(f"MinusSoft{arm}Wins", w); M(f"MinusSoft{arm}Losses", lo)
    sel = e2[e2.combiner == "oof_best_single"].groupby(["arm", "selected"]).size()
    for arm in ("B", "C"):
        M(f"Sel{arm}", ", ".join(f"{m} {c}" for m, c in sel.loc[arm].sort_values(ascending=False).items()))

    # --- E1 macros
    e1, e1s = r["e1"], r["e1s"]
    st = e1.loc["Stacking"]
    M("EoneSeenRows", f"{int(st.n_seen):,}"); M("EoneUnseenRows", int(st.n_unseen))
    M("EoneStackUnseen", f"{100*st.acc_unseen:.2f}")
    for n in ("LR", "NB", "KNN"):
        M(f"Eone{n}Seen", f"{100*e1.loc[n].acc_seen:.2f}")
    M("EoneLRUnseen", f"{100*e1.loc['LR'].acc_unseen:.2f}")
    ov = r["overlap"][r["overlap"].seed.isin(SEEDS)]
    M("EoneOverlapMin", int(ov.seen_rows.min())); M("EoneOverlapMax", int(ov.seen_rows.max()))
    M("EoneOverlapMean", f"{100*(ov.seen_rows/ov.test_rows).mean():.1f}")
    M("EoneSeedsNoUnseen", words(int((ov.seen_rows == ov.test_rows).sum())))
    stk = e1s[e1s.model == "Stacking"]
    M("EoneUnseenPatternInstances", int(stk.unseen_patterns.sum()))
    a42o = r["overlap"][r["overlap"].seed == 42].iloc[0]
    M("AnchorSeen", int(a42o.seen_rows))
    mt = meta  # test rows / groups per seed for grouped protocols
    gC = mt[mt.arm == "C"]
    M("GroupTestRowsMin", int(gC.n_test.min())); M("GroupTestRowsMax", int(gC.n_test.max()))
    M("GroupTestGroups", int(gC.test_groups.iloc[0])); M("GroupDevGroups", int(gC.dev_groups.iloc[0]))
    a42c = r["meta"][(r["meta"].seed == 42) & (r["meta"].arm == "C")].iloc[0]
    M("AnchorCDev", int(a42c.n_dev)); M("AnchorCTest", int(a42c.n_test))

    # --- Table: nested validation
    nv = r["nested"]
    lines = []
    for m in METRICS:
        x = nv.loc[m]
        lines.append(f"{labels[m]} & {f3(x.row_cv_mean)} & {f3(x.group_cv_mean)} & {f3(x.holdout_mean)} & "
                     f"{f3(x.row_cv_mae)} & {f3(x.group_cv_mae)} & {int(x.group_closer)}/{int(x.n_seeds)}\\\\")
    write_tab("nested", lines)
    a = nv.loc["accuracy"]
    M("NestRowCVPct", pct(a.row_cv_mean)); M("NestGroupCVPct", pct(a.group_cv_mean))
    M("NestHoldPct", pct(a.holdout_mean))
    M("NestRowMAE", f"{100*a.row_cv_mae:.2f}"); M("NestGroupMAE", f"{100*a.group_cv_mae:.2f}")
    M("NestAccCloser", int(a.group_closer)); M("NestGroupBias", f"{100*a.group_cv_bias:+.1f}")
    M("NestFoneCloser", int(nv.loc["f1"].group_closer)); M("NestAUCCloser", int(nv.loc["roc_auc"].group_closer))

    # --- Table: preprocessing ablations + tuning
    rows = [("B (row inner)", "B", "Stacking"), ("C (grouped inner)", "C", "Stacking"),
            ("C-dedup", "C_dedup", "Stacking"), ("C-onehot", "C_onehot", "Stacking"),
            ("D (dedup + onehot)", "D", "Stacking"), None, ("D: LR alone", "D", "LR"),
            ("Tuned, cut-off 0.5", "Selected_0.5", "Selected_0.5"),
            ("Tuned, selected cut-off", "Selected_cutoff", "Selected_cutoff")]
    lines = []
    for item in rows:
        if item is None:
            lines.append("\\midrule")
            continue
        label, arm, model = item
        lines.append(f"{label} & " + " & ".join(pm(*stat(rep, arm, model, m))
                                                for m in METRICS) + "\\\\")
    write_tab("ablate", lines)
    for cname, tag in (("C_onehot-C stack", "Onehot"), ("C_dedup-C stack", "Dedup"), ("D-C stack", "DC"),
                       ("D-B stack", "DB"), ("D stack-D LR", "DstackDLR")):
        x = con(r, cname)
        M(f"Abl{tag}Diff", sgn(x.mean_pp, 2)); M(f"Abl{tag}Wins", int(x.wins))
        M(f"Abl{tag}Ties", int(x.ties)); M(f"Abl{tag}Losses", int(x.losses))
    d_st, d_lr = stat(rep, "D", "Stacking", "accuracy")[0], stat(rep, "D", "LR", "accuracy")[0]
    on = stat(rep, "C_onehot", "Stacking", "accuracy")[0]
    M("DStackAcc", f3(d_st)); M("DStackAccPct", f"{100*d_st:.2f}"); M("DStackAccPctShort", pct(d_st))
    M("DLRAcc", f3(d_lr)); M("DLRAccPct", f"{100*d_lr:.2f}"); M("DLRAccPctShort", pct(d_lr))
    M("OnehotHigherThanD", "higher" if on > d_st else "lower")
    s5, sc = stat(rep, "Selected_0.5", "Selected_0.5", "accuracy")[0], stat(rep, "Selected_cutoff", "Selected_cutoff", "accuracy")[0]
    M("TunedAccPct", f"{100*s5:.2f}"); M("TunedCutAccPct", f"{100*sc:.2f}")
    M("TunedCutDirection", "leaves it essentially unchanged" if abs(sc-s5) < 0.001 else ("lowers it" if sc < s5 else "raises it"))
    fam = r["sel"][r["sel"].seed.isin(SEEDS)].family.value_counts()
    full = {"LR": "LR", "SVM": "SVM", "RF": "RF", "XGB": "XGB"}
    M("TunedFamilies", ", ".join(f"{full[f]} in {words(int(c))} seed{'s' if c != 1 else ''}"
                                 for f, c in fam.items()))

    # --- Table: statistics
    lines = []
    for cname, label in (("C-B stack", "C$-$B stack"), ("D-C stack", "D$-$C stack"), ("D-B stack", "D$-$B stack"),
                         ("D stack-C LR", "D stack$-$C LR"), ("D stack-D LR", "D stack$-$D LR")):
        for weighting in ("row", "pattern"):
            x = con(r, cname, "accuracy", weighting)
            hp = "---" if np.isnan(x.holm_p) else f3(x.holm_p)
            lines.append(f"{label} & {weighting} & {sgn(x.mean_pp,2)}\\,$\\pm$\\,{x.sd_pp:.2f} & "
                         f"${x.t_corr:.2f}$ & {f3(x.p_corr)} & {hp}\\\\")
    write_tab("stats", lines)
    M("DBHolmRow", f3(con(r, "D-B stack").holm_p)); M("DBHolmPattern", f3(con(r, "D-B stack", "accuracy", "pattern").holm_p))
    mc = r["mcn"]
    M("McnStackOnly", mc["stack_only_correct"]); M("McnNBOnly", mc["nb_only_correct"])
    M("McnP", f"{mc['mcnemar_exact_p']:.3f}")
    any_reject = (r["con"].holm_p < 0.05).any()
    M("AnyHolmReject", "rejects" if any_reject else "does not reject")

    # --- Appendix: seed-42 confusion counts and D per-model table
    lines = []
    for model in ALL_MODELS:
        a, c = anchor(allm, "A", model), anchor(allm, "C", model)
        label = "Stack" if model == "Stacking" else model
        lines.append(f"{label} & " + " & ".join(str(int(v)) for v in (a.tn, a.fp, a.fn, a.tp, c.tn, c.fp, c.fn, c.tp))
                     + "\\\\")
    write_tab("cm", lines)
    lines = []
    for model in ALL_MODELS:
        label = "Stack" if model == "Stacking" else model
        if model == "Stacking":
            lines.append("\\midrule")
        lines.append(f"{label} & " + " & ".join(pm(*stat(rep, "D", model, m)) for m in METRICS) + "\\\\")
    write_tab("dmodels", lines)


