def stat(rep, arm, model, metric, weighting="row"):
    s = rep[(rep.arm == arm) & (rep.model == model) & (rep.weighting == weighting)][metric]
    assert len(s) == len(SEEDS), (arm, model, metric, len(s))
    return s.mean(), s.std(ddof=1)


def anchor(allm, arm, model):
    s = allm[(allm.seed == 42) & (allm.arm == arm) & (allm.model == model) & (allm.weighting == "row")]
    return s.iloc[0]


def con(r, name, metric="accuracy", weighting="row"):
    c = r["con"]
    return c[(c.contrast == name) & (c.metric == metric) & (c.weighting == weighting)].iloc[0]


