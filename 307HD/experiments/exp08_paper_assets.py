# ------------------------------------------------------------------ helpers
class Macros:
    def __init__(self):
        self.lines = ["% Generated by experiments/exp08_paper_assets.py -- do not edit by hand"]

    def __call__(self, name, value):
        assert name.isalpha(), name
        self.lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    def write(self, path):
        path.write_text("\n".join(self.lines) + "\n")


def f3(x):
    return f"{x:.3f}"


def pm(mean, sd):
    return f"{mean:.3f}\\,$\\pm$\\,{sd:.3f}"


def sgn(x, nd=3):
    s = f"{x:+.{nd}f}"
    return s.replace("-", "$-$")


def pct(x, nd=1):
    return f"{100 * x:.{nd}f}"


def words(n):
    return {0: "zero", 1: "one", 2: "two", 3: "three", 4: "four", 5: "five", 6: "six", 7: "seven",
            8: "eight", 9: "nine", 10: "ten"}.get(n, str(n))


def write_tab(name, lines):
    (GEN / f"tab_{name}.tex").write_text("\n".join(lines) + "\n")


def counts_metrics(tn, fp, fn, tp):
    acc = (tp + tn) / (tn + fp + fn + tp)
    sens, spec = tp / (tp + fn), tn / (tn + fp)
    prec = tp / (tp + fp)
    f1 = 2 * tp / (2 * tp + fp + fn)
    mcc = (tp * tn - fp * fn) / np.sqrt((tp + fp) * (tp + fn) * (tn + fp) * (tn + fn))
    return {"sensitivity": sens, "specificity": spec, "precision": prec, "accuracy": acc, "f1": f1, "mcc": mcc}


